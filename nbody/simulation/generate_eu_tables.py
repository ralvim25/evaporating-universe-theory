# 4. Validation
# ============================================================

def validate():
    """Run sanity checks on EU tables."""
    print("\n=== Validation ===")
    
    # f_cdm checks
    f0 = f_cdm(0.0)
    f_zt = f_cdm(z_trans)
    f_49 = f_cdm(49.0)
    f_7  = f_cdm(7.0)  # just above z_trans
    print(f"f_cdm(z=0)     = {f0:.6f}  (expected ~0.9558)")
    print(f"f_cdm(z_trans)  = {f_zt:.6f}  (expected ~{1 - epsilon_IR*0.5:.6f})")
    print(f"f_cdm(z=7)     = {f_7:.6f}  (expected 1.000000 — Heaviside)")
    print(f"f_cdm(z=49)    = {f_49:.6f}  (expected 1.000000 — Heaviside)")
    
    assert abs(f0 - 0.9558) < 0.001, f"f_cdm(0) = {f0}, expected ~0.9558"
    assert f_49 == 1.0, f"f_cdm(49) = {f_49}, expected EXACTLY 1.0 (Heaviside cutoff)"
    assert f_7 == 1.0, f"f_cdm(7) = {f_7}, expected EXACTLY 1.0 (z > z_trans)"
    
    # Omega checks
    Omega_Lambda_0 = 1.0 - Omega_r - Omega_b - Omega_cdm_prim * f0
    Omega_m_eff_0 = Omega_b + Omega_cdm_prim * f0
    print(f"\nOmega_b         = {Omega_b:.5f}")
    print(f"Omega_cdm_prim  = {Omega_cdm_prim:.5f}")
    print(f"Omega_m_eff(0)  = {Omega_m_eff_0:.5f}")
    print(f"Omega_Lambda(0) = {Omega_Lambda_0:.5f}")
    print(f"Omega_r         = {Omega_r:.6f}")
    print(f"Sum             = {Omega_r + Omega_m_eff_0 + Omega_Lambda_0:.6f} (should be 1.0)")
    
    # Omega_m for param_eu.txt
    Omega_m_param = Omega_b + Omega_cdm_prim  # primordial total
    print(f"\nOmega0 for param_eu.txt = {Omega_m_param:.5f}")
    
    print("\n[OK] All checks passed!")


# ============================================================
# Main
# ============================================================

def main():
    parser = argparse.ArgumentParser(description="Generate eu_tables.h for Gadget-4")
    parser.add_argument("--n-points", type=int, default=10000,
                        help="Number of table points (default: 10000)")
    parser.add_argument("--output", type=str, default="eu_tables.h",
                        help="Output filename (default: eu_tables.h)")
    parser.add_argument("--validate-only", action="store_true",
                        help="Only run validation, don't generate header")
    args = parser.parse_args()
    
    # Validate first
    validate()
    
    if args.validate_only:
        return
    
    # Generate z grid (ascending: 0 → z_max)
    z_max = 49.0
    z_array = np.linspace(0.0, z_max, args.n_points)
    
    # Compute f_cdm
    fcdm_array = np.array([f_cdm(z) for z in z_array])
    
    # Compute E(z) = H_EU(z)/H0
    print("\nComputing H_EU(z) from modified Friedmann equation...")
    E_array = compute_hubble_eu(z_array)
    
    # Sanity: E(z=0) should be ~1.0
    E0 = E_array[0]
    print(f"E(z=0) = {E0:.8f} (should be 1.000000)")
    assert abs(E0 - 1.0) < 0.01, f"E(0) = {E0}, expected ~1.0!"
    
    # Generate header
    generate_header(z_array, fcdm_array, E_array, args.output)
    print(f"\n[OK] {args.output} generated successfully!")


if __name__ == "__main__":
    main()
